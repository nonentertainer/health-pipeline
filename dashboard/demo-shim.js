/* Demo mode: an in-memory stand-in for the dashboard's database.

   The dashboard only knows one thing about its backend: `await window.claude.use("db")`
   returns documents and collections it can subscribe to and write. In production that is
   the artifact's database. Here it is a Map seeded with synthetic data (window.DEMO_DATA,
   generated by tools/build_demo.py through the real pipeline code), so the same page runs
   on static hosting. Writes work and notify listeners; they live until the tab closes.

   The data is built for a fixed week. It is moved forward in whole weeks so that today
   falls inside it (weekdays keep matching the training plan), then cut off at "now". */
(function () {
  const RAW = window.DEMO_DATA;
  if (!RAW) return;
  const pad = n => String(n).padStart(2, "0");
  const iso = d => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
  const parse = s => { const [y, m, d] = s.split("-").map(Number); return new Date(y, m - 1, d); };
  const now = new Date(), today = iso(now), hour = now.getHours() + now.getMinutes() / 60;
  const hhmm = `${pad(now.getHours())}:${pad(now.getMinutes())}`;

  const weeks = Math.ceil(Math.round((parse(today) - parse(RAW.end)) / 864e5) / 7);
  const move = s => { const d = parse(s); d.setDate(d.getDate() + weeks * 7); return iso(d); };
  const D = JSON.parse(JSON.stringify(RAW).replace(/\d{4}-\d{2}-\d{2}/g, move));

  // ---- cut the future off ----
  const fit = D.docs["fitbit/daily"];
  Object.keys(fit.days).forEach(d => { if (d > today) delete fit.days[d]; });
  const t = fit.days[today];
  if (t) {
    const awake = Math.max(0.03, Math.min(1, (hour - 7) / 15));     // share of a 07:00-22:00 day that has passed
    if (hour < 6) ["sleepMin", "deepMin", "remMin", "lightMin", "awakeMin", "sleepStart", "sleepEnd", "hrv", "rhr",
      "fitbitRhr", "rr", "spo2", "tempDelta"].forEach(k => delete t[k]);   // still asleep: no night yet
    const active = t.activeKcal || 0;
    if (t.steps != null) t.steps = Math.round(t.steps * awake);
    if (t.kcal != null) t.kcal = Math.round((t.kcal - active) * hour / 24 + active * awake);
    if (t.activeKcal != null) t.activeKcal = Math.round(active * awake);
    if (t.azm != null) t.azm = Math.round(t.azm * awake);
  }
  fit.workouts = fit.workouts.filter(w => w.date < today || (w.date === today && w.start.slice(11, 16) <= hhmm));
  fit.updated = new Date(now.getTime() - 18 * 60e3).toISOString();
  if (fit.insights) fit.insights.asOf = today;

  const days = D.collections.days.filter(v => v.date <= today);
  const td = days.find(v => v.date === today);
  if (td) { td.sessions = []; td.notes = ""; if (hour < 7) td.weight = null; }   // today's session is the visitor's to log
  const posture = D.collections.posture.filter(v => v.date < today);
  const midnight = parse(today).getTime();
  posture.push({ date: today, lies: [], routine: {}, updatedAt: now.toISOString(),
    rounds: [{ how: "guided", t: new Date(Math.max(midnight + 60e3, now.getTime() - 40 * 60e3)).toISOString() }] });

  // ---- the database ----
  const clone = v => JSON.parse(JSON.stringify(v));
  const docs = new Map(), docSubs = new Map(), colSubs = new Map();
  Object.keys(D.docs).forEach(p => docs.set(p, D.docs[p]));
  days.forEach(v => docs.set("days/" + v.date, v));
  posture.forEach(v => docs.set("posture/" + v.date, v));
  const later = fn => setTimeout(fn, 60);
  const snap = p => ({ id: p.split("/").pop(), exists: docs.has(p), data: () => clone(docs.get(p)) });
  const rows = (name, q) => {
    let out = [...docs.keys()].filter(p => p.startsWith(name + "/") && p.split("/").length === 2).map(snap);
    if (q.field) out.sort((a, b) => { const x = a.data()[q.field], y = b.data()[q.field]; return (x > y ? 1 : x < y ? -1 : 0) * (q.dir === "desc" ? -1 : 1); });
    return { docs: q.n ? out.slice(0, q.n) : out };
  };
  const doc = p => ({
    get: async () => snap(p),
    set: async v => {
      docs.set(p, clone(v));
      later(() => {
        (docSubs.get(p) || []).forEach(cb => cb(snap(p)));
        const name = p.split("/")[0];
        (colSubs.get(name) || []).forEach(s => s.cb(rows(name, s.q)));
      });
    },
    onSnapshot: cb => {
      if (!docSubs.has(p)) docSubs.set(p, []);
      docSubs.get(p).push(cb);
      later(() => cb(snap(p)));
      return () => { const a = docSubs.get(p) || [], i = a.indexOf(cb); if (i >= 0) a.splice(i, 1); };
    }
  });
  const collection = name => {
    const q = {};
    const api = {
      orderBy: (field, dir) => { q.field = field; q.dir = dir || "asc"; return api; },
      limit: n => { q.n = n; return api; },
      doc: id => doc(name + "/" + id),
      get: async () => rows(name, q),
      onSnapshot: cb => {
        const s = { cb, q };
        if (!colSubs.has(name)) colSubs.set(name, []);
        colSubs.get(name).push(s);
        later(() => cb(rows(name, q)));
        return () => { const a = colSubs.get(name) || [], i = a.indexOf(s); if (i >= 0) a.splice(i, 1); };
      }
    };
    return api;
  };
  window.claude = { use: async name => (name === "db" ? { doc, collection } : null) };

  // ---- say that this is a demo ----
  const b = document.createElement("div");
  b.setAttribute("role", "note");
  b.style.cssText = "background:#111318;color:#FFFFFF;border-radius:16px;padding:10px 14px;font-size:13px;line-height:1.45";
  b.innerHTML = '<b>Demo · sahte veri.</b> Sayılar gerçek birine ait değil; yazdıkların yalnızca bu sekmede kalır. ' +
    '<a href="https://github.com/nonentertainer/health-pipeline" style="color:#C8EA21;font-weight:600">GitHub\'da kaynak kod</a>';
  const wrap = document.querySelector(".wrap");
  if (wrap) wrap.insertBefore(b, wrap.firstChild);
})();
